def _norm_pair(en: str, bn: str) -> tuple[str, str]:
    en, bn = en.strip(), bn.strip()
    if not re.search(r"[A-Za-z]", en):
        en = f"value {en}"
    if not re.search(r"[ঀ-৿]", bn):
        # Pure symbol/number: allow en==bn without Bangla, else prefix মান
        raw = bn
        sym = en[6:].strip() if en.startswith("value ") else en
        if sym == raw and not re.search(r"[A-Za-z]{3,}", en):
            bn = raw  # en may still be "value X"; make bn match for symbol rule
            # Validator: missing Bangla if not has_bangla and (en!=bn OR 3+ latin)
            # So set bn == en only when en has no 3+ latin run — "value" is 5 letters!
            # Therefore always add Bangla prefix for numeric-only options.
            bn = f"মান {raw}"
        else:
            bn = f"মান {raw}"
    return en, bn


