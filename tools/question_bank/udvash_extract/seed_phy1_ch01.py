def _norm_pair(en, bn):
    en, bn = en.strip(), bn.strip()
    if en == bn and not re.search(r'[A-Za-z]', en):
        en = f'value {en}'
        bn = f'মান {bn}' if not re.search(r'[ঀ-৿]', bn) else bn
    if en != bn and en.endswith(' x'):
        en = en[:-2].rstrip()
    return en, bn

