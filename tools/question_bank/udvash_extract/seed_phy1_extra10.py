def append_topic(topic_id: str, rows: list[dict]) -> str:
    path = TOPICS / f"{topic_id}.jsonl"
    if not path.exists():
        return f"FAIL missing {topic_id}"
    existing_lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    n = len(existing_lines)
    if n == 30:
        # Idempotent: already appended
        return f"OK already 30 {topic_id}"
    if n != 20:
        return f"FAIL expected 20 lines, found {n}: {topic_id}"
    if len(rows) != 10:
        return f"FAIL need exactly 10 new rows, got {len(rows)}: {topic_id}"

    existing_stems = {json.loads(ln)["stem_en"].strip().lower() for ln in existing_lines}
    new_stems = [r["stem_en"].strip().lower() for r in rows]
    if len(set(new_stems)) != 10:
        return f"FAIL duplicate stems within extra set: {topic_id}"
    overlap = existing_stems.intersection(new_stems)
    if overlap:
        return f"FAIL stem overlap with existing: {topic_id}: {sorted(overlap)[:3]}"

    with path.open("a", encoding="utf-8", newline="\n") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")

    final = len([ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()])
    if final != 30:
        return f"FAIL after append count={final}: {topic_id}"
    return f"OK appended 10 → 30 {topic_id}"


def main() -> None:
    expected = sorted(p.stem for p in TOPICS.glob("phy1_27_*.jsonl"))
    if len(expected) != 41:
        print(f"WARN expected 41 topic files, found {len(expected)}")
    missing_extra = [t for t in expected if t not in EXTRA]
    extra_unknown = [t for t in EXTRA if t not in expected]
    if missing_extra:
        print("FAIL missing EXTRA for:", missing_extra)
    if extra_unknown:
        print("FAIL EXTRA for unknown topics:", extra_unknown)

    ok30 = 0
    fails: list[str] = []
    for topic_id in expected:
        rows = EXTRA.get(topic_id)
        if not rows:
            fails.append(f"no EXTRA {topic_id}")
            continue
        status = append_topic(topic_id, rows)
        print(status)
        if status.startswith("OK"):
            ok30 += 1
        else:
            fails.append(status)

    # Spot-check line counts
    counts = {}
    for p in sorted(TOPICS.glob("phy1_27_*.jsonl")):
        n = len([ln for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()])
        counts[n] = counts.get(n, 0) + 1
    print("--- spot-check ---")
    print("line-count histogram:", counts)
    print(f"topics_at_30={ok30} failures={len(fails)}")
    if fails:
        for f in fails:
            print(" ", f)


if __name__ == "__main__":
    main()
