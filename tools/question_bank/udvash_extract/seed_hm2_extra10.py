def _norm_pair(en: str, bn: str) -> tuple[str, str]:
    en, bn = en.strip(), bn.strip()
    if not re.search(r"[A-Za-z]", en):
        en = f"value {en}"
    if en.startswith("value ") and not re.search(r"[ঀ-৿]", bn):
        bn = "মান " + bn.removeprefix("মান ").strip()
    return en, bn


def _bn_opt(en: str, bn: str) -> str:
    bn = bn.strip()
    if re.search(r"[ঀ-৿]", bn):
        return bn
    if not re.search(r"[A-Za-z]{3,}", en):
        return bn if bn else en
    return f"মান: {bn or en}"


def q(
    stem_en: str,
    stem_bn: str,
    opts_en: list[str],
    opts_bn: list[str],
    correct: str,
    difficulty: str,
    qtype: str,
    exp_en: str,
    exp_bn: str,
) -> dict:
    stem_bn = stem_bn.strip()
    if not re.search(r"[ঀ-৿]", stem_bn):
        stem_bn = stem_bn.rstrip(" =:") + " এর মান কত?"
    opts_bn = [_bn_opt(e, b) for e, b in zip(opts_en, opts_bn)]
    pairs = [_norm_pair(e, b) for e, b in zip(opts_en, opts_bn)]
    (a, ab), (b, bb), (c, cb), (d, db) = pairs
    if not re.search(r"[ঀ-৿]", exp_bn):
        exp_bn = "ব্যাখ্যা: " + exp_bn
    return {
        "stem_en": stem_en.strip(),
        "stem_bn": stem_bn.strip(),
        "option_a_en": a,
        "option_a_bn": ab,
        "option_b_en": b,
        "option_b_bn": bb,
        "option_c_en": c,
        "option_c_bn": cb,
        "option_d_en": d,
        "option_d_bn": db,
        "correct": correct,
        "difficulty": difficulty,
        "type": qtype,
        "explanation_en": exp_en.strip(),
        "explanation_bn": exp_bn.strip(),
        "verified": False,
        "source": SOURCE,
    }


