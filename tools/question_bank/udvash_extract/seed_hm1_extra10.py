def append_topic(topic_id: str, rows: list[dict]) -> dict:
    path = TOPICS / f"{topic_id}.jsonl"
    if not path.exists():
        raise SystemExit(f"missing {path}")
    existing = [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    n = len(existing)
    if n == 30:
        print(f"SKIP {topic_id}: already 30")
        return {"topic_id": topic_id, "count": 30, "appended": 0}
    if n != 20:
        raise SystemExit(f"{topic_id}: expected 20 existing lines, found {n}")
    if len(rows) != 10:
        raise SystemExit(f"{topic_id}: expected 10 new rows, got {len(rows)}")

    old_stems = {r["stem_en"].casefold() for r in existing}
    new_stems = [r["stem_en"].casefold() for r in rows]
    if len(set(new_stems)) != 10:
        raise SystemExit(f"{topic_id}: duplicate stems among new 10")
    clash = old_stems.intersection(new_stems)
    if clash:
        raise SystemExit(f"{topic_id}: stem clash with existing: {next(iter(clash))}")

    for i, r in enumerate(rows, 1):
        err = validate_record(r)
        if err:
            raise SystemExit(f"{topic_id} new#{i}: {err}\n{json.dumps(r, ensure_ascii=False)[:400]}")

    with path.open("a", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    total = n + 10
    print(f"APPEND {topic_id}: {n} -> {total}")
    return {"topic_id": topic_id, "count": total, "appended": 10}


def main() -> None:
    expected = sorted(
        p.stem for p in TOPICS.glob("hm1_27_*.jsonl")
    )
    if set(EXTRA.keys()) != set(expected):
        missing = set(expected) - set(EXTRA.keys())
        extra = set(EXTRA.keys()) - set(expected)
        raise SystemExit(f"topic mismatch missing={missing} extra={extra}")

    results = {}
    for tid in expected:
        results[tid] = append_topic(tid, EXTRA[tid])

    bad = [tid for tid, r in results.items() if r["count"] != 30]
    summary = {
        "paper": "hm1",
        "topics": len(results),
        "all_at_30": not bad,
        "bad": bad,
        "counts": {tid: r["count"] for tid, r in results.items()},
    }
    print(json.dumps({"topics": len(results), "all_at_30": not bad, "bad": bad}, indent=2))
    if bad:
        raise SystemExit(f"not all at 30: {bad}")


if __name__ == "__main__":
    main()

